package ie.intellidesk.service;

import ie.intellidesk.domain.*;
import ie.intellidesk.ml.MlClient;
import ie.intellidesk.ml.MlContract;
import ie.intellidesk.repo.IncidentUpdateRepository;
import ie.intellidesk.repo.UserRepository;
import ie.intellidesk.web.dto.Dtos;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.test.mock.mockito.MockBean;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.transaction.annotation.Transactional;

import java.util.List;
import java.util.Optional;

import static org.assertj.core.api.Assertions.assertThat;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.Mockito.when;

/**
 * What the application does with an AI-assisted draft — and without one.
 *
 * <p>The language model is optional infrastructure, so the rules mirror the ones for
 * the classifier: a missing model is recorded and survived, never fatal; what the
 * agent was shown is stored rather than re-asked; and the draft is a working note for
 * agents, not something the person who raised the ticket sees.
 */
@SpringBootTest
@ActiveProfiles("test")
@Transactional
class AiDraftServiceTest {

    @MockBean
    MlClient ml;

    @Autowired AiDraftService drafts;
    @Autowired IncidentService incidents;
    @Autowired UserRepository users;
    @Autowired IncidentUpdateRepository updates;

    private AppUser employee;
    private AppUser agent;

    @BeforeEach
    void setUp() {
        employee = users.save(new AppUser("Draft Employee", "draft-emp-" + System.nanoTime() + "@test.ie",
                "{noop}x", Role.EMPLOYEE));
        agent = users.save(new AppUser("Draft Agent", "draft-agent-" + System.nanoTime() + "@test.ie",
                "{noop}x", Role.AGENT));
        when(ml.analyse(any())).thenReturn(Optional.empty());
    }

    private Incident raise() {
        return incidents.create(new Dtos.CreateIncidentRequest(
                "Outlook closes when I open a PDF", "Every attachment crashes it.",
                Impact.MEDIUM, Urgency.HIGH), employee);
    }

    private static MlContract.DraftResponse draft(String status, List<MlContract.DraftStep> steps,
                                                  boolean injection) {
        return new MlContract.DraftResponse(
                status, "Outlook crashes on PDF attachments.", steps,
                "We are looking into this now.", "high",
                "drafted".equals(status) ? "" : "Nothing retrieved matches.",
                List.of(new MlContract.DraftSource("INC-100121", "Outlook closes itself",
                        "Disabled the conflicting preview add-in.", 0.81)),
                new MlContract.DraftGuards(injection, injection ? List.of("override-instructions") : List.of(),
                        0, 0, 0, false),
                new MlContract.DraftTrace("test-llm", 2, List.of(), 900, 80, 4200),
                "d1-agent-1");
    }

    private List<String> trail(Incident incident) {
        return updates.findByIncidentIdOrderByCreatedAtAsc(incident.getId()).stream()
                .map(IncidentUpdate::getComment).toList();
    }

    @Test
    void aMissingLanguageModelIsRecordedNotFatal() {
        when(ml.draft(anyString(), anyString(), any())).thenReturn(Optional.empty());
        Incident incident = raise();

        boolean drafted = drafts.draft(incident.getId(), agent);

        assertThat(drafted).isFalse();
        assertThat(incidents.detail(incident.getId()).aiDraft()).isNull();
        assertThat(trail(incident)).anyMatch(c -> c.contains("language model is unavailable"));
    }

    @Test
    void aDraftIsStoredWithItsCitationsInTheTrail() {
        when(ml.draft(anyString(), anyString(), any())).thenReturn(Optional.of(draft("drafted",
                List.of(new MlContract.DraftStep("Disabled the conflicting preview add-in.",
                        "INC-100121", "Outlook closes itself")), false)));
        Incident incident = raise();

        assertThat(drafts.draft(incident.getId(), agent)).isTrue();

        Dtos.IncidentDetail detail = incidents.detail(incident.getId());
        assertThat(detail.aiDraft().status()).isEqualTo("drafted");
        assertThat(detail.aiDraft().steps()).extracting(MlContract.DraftStep::source).containsExactly("INC-100121");
        assertThat(detail.aiDraftAt()).isNotNull();
        assertThat(trail(incident)).anyMatch(c -> c.contains("AI draft generated by test-llm from INC-100121"));
    }

    @Test
    void anAbstentionIsStoredAndExplained() {
        when(ml.draft(anyString(), anyString(), any())).thenReturn(Optional.of(draft("abstained", List.of(), false)));
        Incident incident = raise();

        assertThat(drafts.draft(incident.getId(), agent)).isTrue();

        assertThat(incidents.detail(incident.getId()).aiDraft().status()).isEqualTo("abstained");
        assertThat(trail(incident)).anyMatch(c -> c.contains("AI declined to draft"));
    }

    @Test
    void suspectedPromptInjectionIsWrittenToTheAuditTrail() {
        when(ml.draft(anyString(), anyString(), any())).thenReturn(Optional.of(draft("drafted",
                List.of(new MlContract.DraftStep("Disabled the conflicting preview add-in.",
                        "INC-100121", "Outlook closes itself")), true)));
        Incident incident = raise();

        drafts.draft(incident.getId(), agent);

        assertThat(trail(incident)).anyMatch(c -> c.contains("prompt-injection") && c.contains("override-instructions"));
    }

    @Test
    void theEmployeeWhoRaisedTheTicketDoesNotSeeTheDraft() {
        when(ml.draft(anyString(), anyString(), any())).thenReturn(Optional.of(draft("drafted",
                List.of(new MlContract.DraftStep("Disabled the conflicting preview add-in.",
                        "INC-100121", "Outlook closes itself")), false)));
        Incident incident = raise();
        drafts.draft(incident.getId(), agent);

        assertThat(incidents.detailFor(incident.getId(), agent).aiDraft()).isNotNull();
        assertThat(incidents.detailFor(incident.getId(), employee).aiDraft()).isNull();
    }
}
